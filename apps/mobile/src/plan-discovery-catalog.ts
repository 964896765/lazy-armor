export const PLAN_SCENES: readonly PlanScene[] = sceneSeeds.map(([domain, title, taskTypes]) => ({
  domain, title, taskTypes,
  description: descriptions[title] ?? intentDescription[taskTypes[0] ?? '计划'],
}));
export function scenesForPlanFilter(domain: PlanDomain, taskType: PlanTaskType, search = ''): PlanScene[] {
  const needle = search.trim().toLocaleLowerCase('zh-CN');
  return PLAN_SCENES.filter((scene) => (domain === '推荐' || scene.domain === domain) && (taskType === '全部' || scene.taskTypes.includes(taskType)) && (!needle || `${scene.title} ${scene.description} ${scene.domain}`.toLocaleLowerCase('zh-CN').includes(needle)));
}
