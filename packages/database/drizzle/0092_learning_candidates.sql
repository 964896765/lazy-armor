CREATE TABLE learning_candidates (
  id binary(16) NOT NULL PRIMARY KEY,
  user_id binary(16) NOT NULL,
  evidence_id binary(16) NOT NULL,
  settings_version int NOT NULL,
  source_json json NOT NULL,
  source_hash char(64) NOT NULL,
  proposal_hash char(64) NOT NULL,
  title varchar(120) NULL,
  content text NULL,
  status varchar(16) NOT NULL,
  version int NOT NULL,
  confirmation_hash char(64) NULL,
  memory_id binary(16) NULL,
  confirmed_memory_version int NULL,
  expires_at datetime(6) NOT NULL,
  created_at datetime(6) NOT NULL,
  updated_at datetime(6) NOT NULL,
  UNIQUE KEY learning_candidate_owner_evidence_uq (user_id, evidence_id),
  KEY learning_candidate_owner_created_idx (user_id, created_at, id),
  CONSTRAINT learning_candidate_owner_fk FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT learning_candidate_evidence_fk FOREIGN KEY (evidence_id) REFERENCES verification_evidence(id),
  CONSTRAINT learning_candidate_memory_fk FOREIGN KEY (memory_id) REFERENCES personal_memories(id)
);
